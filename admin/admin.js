async function render() {
  if (!me) {
    app.innerHTML = loginView();
    return;
  }
  const r = route();
  if (r.page === "overview") {
    const data = await api("/api/admin/overview");
    app.innerHTML = shell("overview", {
      top: `<h1>${T.overview}</h1>`,
      body: `
        <div class="cards">
          <div class="card"><span>${T.pending}</span><strong>${data.counts.pending_review}</strong></div>
          <div class="card"><span>${T.approved}</span><strong>${data.counts.approved}</strong></div>
          <div class="card"><span>${T.needs}</span><strong>${data.counts.needs_information}</strong></div>
          <div class="card"><span>${T.rejected}</span><strong>${data.counts.rejected}</strong></div>
          <div class="card"><span>${T.blocked}</span><strong>${data.counts.blocked || 0}</strong></div>
        </div>
        <div class="panel">
          <h2>${T.latest}</h2>
          ${appRows(data.latest)}
        </div>`,
    });
    return;
  }
  if (r.page === "detail") {
    detail = await api("/api/admin/applications/" + r.id);
  }
  const status = filter;
  const rows = await api("/api/admin/applications?status=" + encodeURIComponent(status) + "&q=" + encodeURIComponent(query));
  const chips = [
    ["", T.all],
    ["pending_review", T.pending],
    ["approved", T.approved],
    ["needs_information", T.needs],
    ["rejected", T.rejected],
    ["blocked", T.blocked],
  ].map(([id, label]) => `<button class="chip${filter === id ? " is-on" : ""}" data-filter="${id}" type="button">${label}</button>`).join("");
  app.innerHTML = shell("apps", {
    top: `<h1>${T.apps}</h1>`,
    body: `
      <div class="tools">
        <div class="filters">${chips}</div>
        <input class="field search" data-search value="${esc(query)}" placeholder="${T.search}">
      </div>
      ${appRows(rows)}`,
  });
}

app.addEventListener("submit", async (e) => {
  if (e.target.id === "loginForm") {
    e.preventDefault();
    const fd = new FormData(e.target);
    try {
      me = await api("/api/auth/login", { method: "POST", body: JSON.stringify({ email: fd.get("email"), password: fd.get("password") }) });
      render();
    } catch {
      app.innerHTML = loginView(T.badLogin);
    }
    return;
  }
  const act = e.target.dataset.act;
  const targetId = (actionRow && actionRow.id) || (detail && detail.id);
  if (!act || !targetId) return;
  e.preventDefault();
  const fd = new FormData(e.target);
  const btn = e.target.querySelector("[type=submit]");
  if (btn) btn.disabled = true;
  try {
    if (act === "approve") await api("/api/admin/applications/" + targetId + "/approve", { method: "POST", body: "{}" });
    if (act === "info") await api("/api/admin/applications/" + targetId + "/request-information", { method: "POST", body: JSON.stringify({ message: fd.get("message") }) });
    if (act === "reject") await api("/api/admin/applications/" + targetId + "/reject", { method: "POST", body: JSON.stringify({ reason: fd.get("reason") }) });
    if (act === "block") await api("/api/admin/applications/" + targetId + "/block", { method: "POST", body: "{}" });
    if (act === "delete") {
      await api("/api/admin/applications/" + targetId + "/delete", { method: "POST", body: "{}" });
      if (detail && detail.id === targetId) detail = null;
      actionRow = null;
      modal = null;
      if (pathOf().startsWith("/admin/business-applications/")) go("/admin/business-applications");
      else render();
      return;
    }
    modal = null;
    actionRow = null;
    if (detail && detail.id === targetId) detail = await api("/api/admin/applications/" + targetId);
    render();
  } catch {
    if (btn) btn.disabled = false;
  }
});

app.addEventListener("click", (e) => {
  const a = e.target.closest("a[href^='/admin']");
  if (a) {
    e.preventDefault();
    sideOpen = false;
    go(a.getAttribute("href"));
    return;
  }
  if (e.target.closest("[data-logout]")) {
    api("/api/auth/logout", { method: "POST", body: "{}" }).finally(() => {
      me = null;
      render();
    });
    return;
  }
  if (e.target.closest("[data-menu]")) {
    sideOpen = !sideOpen;
    document.querySelector(".side")?.classList.toggle("is-open", sideOpen);
    return;
  }
  const open = e.target.closest("[data-open]");
  if (open) {
    go("/admin/business-applications/" + open.dataset.open);
    return;
  }
  if (e.target.closest("[data-filter]")) {
    filter = e.target.closest("[data-filter]").dataset.filter;
    render();
    return;
  }
  if (e.target.closest("[data-modal]")) {
    const btn = e.target.closest("[data-modal]");
    modal = btn.dataset.modal;
    if (btn.dataset.id) {
      actionRow = { id: btn.dataset.id, business_name: btn.dataset.name || "", contact: btn.dataset.contact || "" };
    } else if (detail) {
      actionRow = {
        id: detail.id,
        business_name: detail.business_name,
        contact: (detail.contact_first_name + " " + detail.contact_last_name).trim(),
      };
    }
    render();
    return;
  }
  if (e.target.closest("button[data-close-modal]")) {
    e.preventDefault();
    modal = null;
    render();
    return;
  }
  if (e.target.classList.contains("modal-bg")) {
    modal = null;
    render();
    return;
  }
  if (e.target.classList.contains("drawer-bg") || e.target.closest("button[data-close-detail]")) {
    if (e.target.closest("[data-stop]") && !e.target.closest("button[data-close-detail]")) return;
    detail = null;
    modal = null;
    if (pathOf().startsWith("/admin/business-applications/")) go("/admin/business-applications");
    else render();
  }
});

app.addEventListener("input", (e) => {
  if (!e.target.matches("[data-search]")) return;
  clearTimeout(app._q);
  app._q = setTimeout(() => {
    query = e.target.value.trim();
    render();
  }, 220);
});

window.addEventListener("popstate", render);

api("/api/auth/me")
  .then((user) => { me = user; render(); })
  .catch(() => { me = null; render(); });
