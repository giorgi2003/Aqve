app.addEventListener("drop", async (e) => {
  const row = e.target.closest(".mc-cat[data-select-cat]");
  if (!row || !dragCatId) return;
  e.preventDefault();
  const toId = row.dataset.selectCat;
  if (toId === dragCatId) return;
  const cats = await api("/api/business/" + bizId + "/categories");
  const order = cats.map((c) => c.id);
  const from = order.indexOf(dragCatId);
  const to = order.indexOf(toId);
  if (from < 0 || to < 0) return;
  order.splice(from, 1);
  order.splice(to, 0, dragCatId);
  dragCatId = "";
  await applyCatOrder(order);
});

