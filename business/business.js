function socialHandle(url, host) {
  const raw = String(url || "").trim();
  if (!raw) return "";
  let s = raw.replace(/^https?:\/\//i, "").replace(/^www\./i, "");
  const prefix = host + "/";
  if (s.toLowerCase() === host) return "";
  if (s.toLowerCase().startsWith(prefix)) {
    s = s.slice(prefix.length);
  } else if (!s.includes("/") && !/^https?:\/\//i.test(raw) && !s.toLowerCase().includes(host)) {
    return s.replace(/^@/, "").replace(/\/+$/, "");
  } else {
    return raw;
  }
  s = s.replace(/\/+$/, "").replace(/^@/, "");
  return s;
}

function socialHref(handle, host, original) {
  const h = String(handle || "").trim().replace(/^@/, "").replace(/^\/+/, "");
  if (h === socialHandle(original, host)) return String(original || "").trim();
  if (!h) return "";
  if (/^https?:\/\//i.test(h)) return h;
  const stripped = h.replace(/^https?:\/\//i, "").replace(/^www\./i, "");
  if (stripped.toLowerCase().startsWith(host + "/")) return "https://www." + stripped;
  return "https://www." + host + "/" + stripped;
}

function isFilledSocial(url, host) {
  return Boolean(socialHandle(url, host));
}

