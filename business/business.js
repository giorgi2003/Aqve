async function openProduct(id) {
  const cats = await api("/api/business/" + bizId + "/categories");
  if (!cats.length) {
    notice = T.needCat;
    render();
    return;
  }
  const products = id ? await api("/api/business/" + bizId + "/products") : [];
  const item = products.find((p) => p.id === id);
  drawer = productDrawer(cats, item, id ? null : menuCatId);
  app.innerHTML = shell(pageOf(), await menuView());
  bind();
  bindCreator(item);
}

async function applyCatOrder(order) {
  await api("/api/business/" + bizId + "/categories/reorder", { method: "POST", body: JSON.stringify({ order }) });
  render();
}

async function reorder(id, dir) {
  const cats = await api("/api/business/" + bizId + "/categories");
  const order = cats.map((c) => c.id);
  const i = order.indexOf(id);
  const j = i + dir;
  if (i < 0 || j < 0 || j >= order.length) return;
  const tmp = order[i];
  order[i] = order[j];
  order[j] = tmp;
  await applyCatOrder(order);
}

