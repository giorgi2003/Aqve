async function boot() {
  const params = new URLSearchParams(location.search);
  try {
    me = await api("/api/business/session");
  } catch (err) {
    if (err.code === "pending_review" || err.code === "needs_information") {
      app.innerHTML = gate(T.brand, T.pending);
      return;
    }
    if (err.code === "rejected") {
      app.innerHTML = gate(T.brand, T.rejected);
      return;
    }
    if (err.code === "blocked" || err.code === "no_business") {
      app.innerHTML = gate(T.brand, T.noBiz);
      return;
    }
    app.innerHTML = loginView();
    document.getElementById("loginForm").onsubmit = async (e) => {
      e.preventDefault();
      const fd = new FormData(e.target);
      try {
        await api("/api/business/login", { method: "POST", body: JSON.stringify({ email: fd.get("email"), password: fd.get("password") }) });
        boot();
      } catch {
        app.innerHTML = loginView(T.badLogin);
        bindLogin();
      }
    };
    return;
  }
  const wanted = params.get("b");
  if (wanted && me.businesses.some((b) => b.id === wanted)) bizId = wanted;
  else if (me.businesses.length === 1) bizId = me.businesses[0].id;
  else if (me.businesses.length && !bizId) bizId = me.businesses[0].id;
  if (wanted && wanted !== bizId) {
    app.innerHTML = gate(T.brand, T.noBiz);
    return;
  }
  if (!bizId) {
    app.innerHTML = gate(T.brand, T.noBiz);
    return;
  }
  if (!params.get("b") && me.businesses.length) {
    const url = new URL(location.href);
    url.searchParams.set("b", bizId);
    history.replaceState({}, "", url.pathname + url.search);
  }
  await render();
}

