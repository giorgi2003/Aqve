function esc(v) {
  return String(v ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}

function labelOf(list, id) {
  return Apps.store.labelOf(list, id) || id || "\u2014";
}

function fmtDate(iso) {
  if (!iso) return "\u2014";
  try {
    return new Date(iso).toLocaleString("ka-GE", { dateStyle: "medium", timeStyle: "short" });
  } catch {
    return iso;
  }
}

function pathOf() {
  return location.pathname.replace(/\/+$/, "") || "/admin";
}

async function api(url, opts) {
  const res = await fetch(url, {
    credentials: "include",
    headers: { "Content-Type": "application/json", ...(opts && opts.headers) },
    ...opts,
  });
  const body = await res.json().catch(() => ({}));
  if (!res.ok) {
    const err = new Error(body.code || "error");
    err.status = res.status;
    err.code = body.code;
    err.errors = body.errors;
    throw err;
  }
  return body;
}

function route() {
  const p = pathOf();
  if (p === "/admin/business-applications") return { page: "apps" };
  const m = p.match(/^\/admin\/business-applications\/([^/]+)$/);
  if (m) return { page: "detail", id: m[1] };
  return { page: "overview" };
}

