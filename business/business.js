function readImage(file, kind) {
  return new Promise((resolve, reject) => {
    if (!file || !file.size) return resolve("");
    if (!["image/jpeg", "image/png", "image/webp"].includes(file.type)) {
      reject(new Error("type"));
      return;
    }
    if (file.size > 15 * 1024 * 1024) {
      reject(new Error("size"));
      return;
    }
    const img = new Image();
    const objectUrl = URL.createObjectURL(file);
    img.onload = () => {
      URL.revokeObjectURL(objectUrl);
      const maxW = kind === "logo" ? 800 : kind === "cover-original" ? 2400 : kind === "cover" ? 1600 : 1400;
      let w = img.naturalWidth || img.width;
      let h = img.naturalHeight || img.height;
      if (w > maxW) {
        h = Math.round(h * (maxW / w));
        w = maxW;
      }
      const canvas = document.createElement("canvas");
      canvas.width = w;
      canvas.height = h;
      const ctx = canvas.getContext("2d");
      ctx.drawImage(img, 0, 0, w, h);
      let quality = 0.86;
      let out = canvas.toDataURL("image/jpeg", quality);
      while (dataUrlBytes(out) > 1.8 * 1024 * 1024 && quality > 0.48) {
        quality -= 0.08;
        out = canvas.toDataURL("image/jpeg", quality);
      }
      if (dataUrlBytes(out) > 1.8 * 1024 * 1024) {
        reject(new Error("size"));
        return;
      }
      resolve(out);
    };
    img.onerror = () => {
      URL.revokeObjectURL(objectUrl);
      reject(new Error("type"));
    };
    img.src = objectUrl;
  });
}

const AQVE_COVER = { w: 1600, h: 900, minW: 1200, minH: 675, maxZoom: 3 };

function clampCover(n, min, max) {
  return Math.min(max, Math.max(min, n));
}

function loadHtmlImage(src) {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => resolve(img);
    img.onerror = () => reject(new Error("type"));
    img.src = src;
  });
}

function aqveCoverOutputSize(nw, nh, zoom) {
  const cover = Math.max(AQVE_COVER.w / nw, AQVE_COVER.h / nh) * zoom;
  if (cover <= 1) return { w: AQVE_COVER.w, h: AQVE_COVER.h };
  let w = Math.round(AQVE_COVER.w / cover);
  w = Math.max(320, w - (w % 2));
  return { w, h: Math.round(w * 9 / 16) };
}

function exportAqveCover(img, crop) {
  const nw = img.naturalWidth || img.width;
  const nh = img.naturalHeight || img.height;
  const zoom = clampCover(Number(crop.zoom) || 1, 1, AQVE_COVER.maxZoom);
  const x = clampCover(Number(crop.x) || 50, 0, 100);
  const y = clampCover(Number(crop.y) || 50, 0, 100);
  const { w: outW, h: outH } = aqveCoverOutputSize(nw, nh, zoom);
  const scale = Math.max(outW / nw, outH / nh) * zoom;
  const dw = nw * scale;
  const dh = nh * scale;
  const canvas = document.createElement("canvas");
  canvas.width = outW;
  canvas.height = outH;
  const ctx = canvas.getContext("2d");
  ctx.fillStyle = "#16131f";
  ctx.fillRect(0, 0, outW, outH);
  ctx.imageSmoothingEnabled = true;
  ctx.imageSmoothingQuality = "high";
  ctx.drawImage(img, (outW - dw) * (x / 100), (outH - dh) * (y / 100), dw, dh);
  let quality = 0.86;
  let out = canvas.toDataURL("image/jpeg", quality);
  while (dataUrlBytes(out) > 1.8 * 1024 * 1024 && quality > 0.48) {
    quality -= 0.08;
    out = canvas.toDataURL("image/jpeg", quality);
  }
  if (dataUrlBytes(out) > 1.8 * 1024 * 1024) throw new Error("size");
  return out;
}

async function imageUrlToOriginal(url) {
  const res = await fetch(url, { credentials: "same-origin" });
  if (!res.ok) throw new Error("type");
  const blob = await res.blob();
  const type = blob.type && blob.type.startsWith("image/") ? blob.type : "image/jpeg";
  const file = new File([blob], "original.jpg", { type });
  return readImage(file, "cover-original");
}

