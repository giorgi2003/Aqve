function paintInfoPreview(data) {
  const body = document.querySelector("[data-preview-body]");
  if (!body) return;
  let live = body.querySelector(".studio-live");
  if (!live) {
    body.insertAdjacentHTML("afterbegin", infoPreviewHTML(data));
    live = body.querySelector(".studio-live");
  }
  const name = live.querySelector("[data-live-name]");
  if (name) name.textContent = data.name || T.name;
  const meta = live.querySelector("[data-live-meta]");
  if (meta) {
    const types = (Apps && Apps.BUSINESS_TYPES) || [];
    const cities = (Apps && Apps.CITIES) || [];
    meta.textContent = [labelOfList(types, data.business_type), labelOfList(cities, data.city)].filter(Boolean).join(" \u2022 ");
  }
  const short = live.querySelector("[data-live-short]");
  if (short) {
    const text = String(data.short_description || "").trim();
    short.textContent = text;
    short.classList.toggle("is-empty", !text);
  }
  const cover = live.querySelector(".studio-cover");
  if (cover) {
    cover.classList.toggle("has-photo", Boolean(data.cover));
    let img = cover.querySelector("img:not(.studio-logo)");
    let empty = cover.querySelector(".studio-cover-empty");
    if (data.cover) {
      if (!img) {
        img = document.createElement("img");
        img.alt = "";
        cover.insertBefore(img, cover.firstChild);
      }
      if (img.getAttribute("src") !== data.cover) img.src = data.cover;
      if (empty) empty.remove();
    } else {
      if (img) img.remove();
      if (!cover.querySelector(".studio-cover-empty")) {
        cover.insertAdjacentHTML("afterbegin", `<div class="studio-cover-empty">${studioIco("store")}</div>`);
      }
    }
    const letter = (data.name || "A").slice(0, 1).toUpperCase();
    let logo = cover.querySelector(".studio-logo");
    if (data.logo) {
      if (!logo || logo.tagName !== "IMG") {
        if (logo) logo.remove();
        cover.insertAdjacentHTML("beforeend", `<img class="studio-logo" src="${esc(data.logo)}" alt="">`);
      } else if (logo.getAttribute("src") !== data.logo) {
        logo.src = data.logo;
      }
    } else if (!logo || logo.tagName === "IMG") {
      if (logo) logo.remove();
      cover.insertAdjacentHTML("beforeend", `<span class="studio-logo studio-logo-ph">${esc(letter)}</span>`);
    } else {
      logo.textContent = letter;
    }
  }
  const facts = live.querySelector(".studio-live-facts");
  if (facts) {
    const fb = isFilledSocial(data.facebook, SOCIAL_HOST.facebook);
    const ig = isFilledSocial(data.instagram, SOCIAL_HOST.instagram);
    facts.innerHTML = `
      ${data.address ? `<span>${studioIco("pin")}<em>${esc(data.address)}</em></span>` : ""}
      ${data.phone ? `<span>${studioIco("phone")}<em>${esc(data.phone)}</em></span>` : ""}
      ${fb || ig ? `<span class="studio-live-social">${fb ? "<b>Facebook</b>" : ""}${ig ? "<b>Instagram</b>" : ""}</span>` : ""}`;
  }
  const complete = body.querySelector("[data-complete-box]");
  if (complete) complete.innerHTML = infoCompletenessHTML(data);
}

function syncInfoStudio() {
  const form = document.getElementById("infoForm");
  if (!form) return;
  const data = infoFormState(form);
  paintInfoPreview(data);
  ["short_description", "description"].forEach((name) => {
    const el = form.elements[name];
    const count = form.querySelector(`[data-count="${name}"]`);
    if (el && count) count.textContent = el.value.length + " / " + INFO_LIMITS[name];
  });
  const box = document.querySelector("[data-studio-save]");
  if (!box || box.dataset.studioSave === "saving") return;
  const dirty = infoSnap(form) !== form.dataset.snap;
  const next = dirty ? "unsaved" : "saved";
  if (box.dataset.studioSave !== next) setStudioSave(next);
}

